export interface TestCardTextSection {
  label: string;
  value?: string | null;
}

export interface TestCardTextInput {
  title: string;
  context?: string | null;
  dataStatus?: string | null;
  sections: TestCardTextSection[];
  provenance?: Record<string, string | null> | null;
  footerNote?: string | null;
}

/** Stable filename suitable for a downloaded, readable text card. */
export function safeTextFilename(value: string): string {
  const slug = value
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-zA-Z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .toLowerCase()
    .slice(0, 72)
    .replace(/-+$/g, "");
  return slug || "adjacent-test-card";
}

/** Format a test card as editorial, human-readable text — never JSON. */
export function formatTestCardText(input: TestCardTextInput): string {
  const lines = [
    "ADJACENT / CULTURAL INTELLIGENCE",
    "EXPERIMENT TEST CARD",
    "=".repeat(54),
    input.title.trim() || "Untitled experiment",
  ];

  if (input.context?.trim()) lines.push("", input.context.trim());
  if (input.dataStatus?.trim()) lines.push("DATA STATUS: " + input.dataStatus.trim().toUpperCase());

  for (const section of input.sections) {
    if (!section.value?.trim()) continue;
    lines.push(
      "",
      section.label.trim().toUpperCase(),
      "-".repeat(Math.min(54, Math.max(8, section.label.trim().length))),
      section.value.trim(),
    );
  }

  const provenance = Object.entries(input.provenance ?? {}).filter(([, value]) => value?.trim());
  if (provenance.length) {
    lines.push("", "PROVENANCE", "----------");
    for (const [key, value] of provenance) {
      lines.push(key.replace(/_/g, " ").toUpperCase() + ": " + value?.trim());
    }
  }

  if (input.footerNote?.trim()) {
    lines.push("", "INTERPRETATION LIMIT", "--------------------", input.footerNote.trim());
  }

  lines.push("", "Generated by Adjacent. Review the evidence status before acting.");
  return lines.join("\n").replace(/\n{3,}/g, "\n\n").trimEnd() + "\n";
}

/** Download a plain-text file using the browser's native download behavior. */
export function downloadTextFile(filename: string, content: string): void {
  const safeName = filename.toLowerCase().endsWith(".txt") ? filename : filename + ".txt";
  const blob = new Blob([content], { type: "text/plain;charset=utf-8" });
  const objectUrl = URL.createObjectURL(blob);
  const anchor = document.createElement("a");
  anchor.href = objectUrl;
  anchor.download = safeName;
  anchor.style.display = "none";
  document.body.appendChild(anchor);
  anchor.click();
  anchor.remove();
  window.setTimeout(() => URL.revokeObjectURL(objectUrl), 1000);
}
