"""Programme Bet — the decision layer.

Consumes ranked cohorts, taste profile, and geographic evidence to produce
a testable programming hypothesis.  NOT generated by an LLM.

The Programme Bet does NOT claim "X will increase attendance."
It says: "Test programming that connects [existing cultural profile]
with [adjacent cultural group]."

M11 UPGRADE: Two-sided scoring evaluates:
A. Current-audience compatibility — does the candidate fit the existing programme?
B. Adjacent-cohort reach — does the candidate have evidence of reaching the target?

Both sides use measured Qloo evidence already supported by the architecture.
No attendance lift, conversion probability, revenue, or predicted ticket sales.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any

from .geography import GeographyResult


@dataclass(frozen=True)
class ProgrammeBet:
    """A testable programming hypothesis backed by Qloo evidence."""

    # The primary bet
    primary_domain: str
    primary_cohort_name: str
    primary_mean_affinity: float
    primary_member_count: int

    # Runner-up
    runner_up_domain: str | None = None
    runner_up_cohort_name: str | None = None
    runner_up_mean_affinity: float | None = None

    # Two-sided signals (M11.3: renamed for scientific accuracy)
    # Dimension A: How strongly the cohort is adjacent to the programme
    # (mean affinity from Qloo scoring — measures cultural proximity)
    programme_adjacency: float | None = None
    adjacency_band: str | None = None  # High/Medium/Low
    adjacency_call_id: str | None = None
    
    # Dimension B: What fraction of the cohort clears the quality threshold
    # (qualifying_members / total_members — measures cohort breadth)
    cohort_breadth: float | None = None
    breadth_band: str | None = None  # High/Medium/Low
    breadth_call_id: str | None = None
    
    # Evidence
    why: str = ""
    cultural_bridge: str = ""
    geographic_signal: str = ""
    programming_direction: str = ""
    falsification_condition: str = ""
    
    # Rejected candidates
    rejected_candidates: list[dict[str, Any]] = field(default_factory=list)
    
    # Provenance
    primary_call_id: str | None = None
    runner_up_call_id: str | None = None
    geography_call_id: str | None = None
    data_status: str = "measured"

    def to_dict(self) -> dict[str, Any]:
        return {
            "primary": {
                "domain": self.primary_domain,
                "cohort_name": self.primary_cohort_name,
                "mean_affinity": self.primary_mean_affinity,
                "member_count": self.primary_member_count,
                "call_id": self.primary_call_id,
            },
            "runner_up": {
                "domain": self.runner_up_domain,
                "cohort_name": self.runner_up_cohort_name,
                "mean_affinity": self.runner_up_mean_affinity,
                "call_id": self.runner_up_call_id,
            } if self.runner_up_domain else None,
            "two_sided_signals": {
                "programme_adjacency": self.programme_adjacency,
                "adjacency_band": self.adjacency_band,
                "adjacency_call_id": self.adjacency_call_id,
                "cohort_breadth": self.cohort_breadth,
                "breadth_band": self.breadth_band,
                "breadth_call_id": self.breadth_call_id,
                "methodology_note": (
                    "Programme adjacency: mean affinity of cohort members "
                    "against programme taste profile (Qloo /v2/insights). "
                    "Cohort breadth: fraction of cohort members above "
                    "Medium affinity threshold."
                ),
            },
            "why": self.why,
            "cultural_bridge": self.cultural_bridge,
            "geographic_signal": self.geographic_signal,
            "programming_direction": self.programming_direction,
            "falsification_condition": self.falsification_condition,
            "rejected_candidates": self.rejected_candidates,
            "geography_call_id": self.geography_call_id,
            "data_status": self.data_status,
        }


def build_programme_bet(
    ranked_cohorts: list[Any],
    taste_tags: list[Any],
    geography: GeographyResult | None,
    resolved_names: list[str],
    *,
    programme_adjacency_scores: dict[str, float] | None = None,
    cohort_breadth_scores: dict[str, float] | None = None,
    programme_adjacency_bands: dict[str, str] | None = None,
    cohort_breadth_bands: dict[str, str] | None = None,
    programme_adjacency_call_ids: dict[str, str] | None = None,
    cohort_breadth_call_ids: dict[str, str] | None = None,
    rejected_cohorts: list[Any] | None = None,
) -> ProgrammeBet | None:
    """Build a Programme Bet from ranked cohorts and evidence.

    Returns None if insufficient evidence to form a bet.

    Two-sided evaluation:
    A. Programme adjacency: mean affinity of cohort members against programme
       taste profile. Measures cultural proximity. Source: Qloo /v2/insights.
    B. Cohort breadth: fraction of cohort members above Medium affinity threshold.
       Measures how much of the cohort clears the quality bar.
       Source: same Qloo /v2/insights call.

    Both dimensions use the SAME Qloo scoring call but measure different aspects:
    - Adjacency measures STRENGTH of the signal
    - Breadth measures COVERAGE of the signal
    """
    if not ranked_cohorts or len(ranked_cohorts) < 1:
        return None

    primary = ranked_cohorts[0]
    runner_up = ranked_cohorts[1] if len(ranked_cohorts) > 1 else None

    # Extract primary cohort info
    primary_domain = primary.domain.replace("urn:entity:", "") if hasattr(primary, "domain") else "unknown"
    primary_members = primary.members if hasattr(primary, "members") else []
    primary_names = [m.name for m in primary_members[:5] if m.name] if primary_members else []
    primary_affinity = primary.score.mean_affinity if hasattr(primary, "score") and primary.score else 0.0
    primary_call_id = primary.score.call_id if hasattr(primary, "score") and primary.score else None

    # Extract runner-up info
    ru_domain = None
    ru_names = []
    ru_affinity = None
    ru_call_id = None
    if runner_up:
        ru_domain = runner_up.domain.replace("urn:entity:", "") if hasattr(runner_up, "domain") else None
        ru_members = runner_up.members if hasattr(runner_up, "members") else []
        ru_names = [m.name for m in ru_members[:3] if m.name] if ru_members else []
        ru_affinity = runner_up.score.mean_affinity if hasattr(runner_up, "score") and runner_up.score else None
        ru_call_id = runner_up.score.call_id if hasattr(runner_up, "score") and runner_up.score else None

    # Two-sided signals (M11.3: renamed for scientific accuracy)
    primary_cohort_id = primary.cohort_id if hasattr(primary, "cohort_id") else None
    adjacency_score = (programme_adjacency_scores or {}).get(primary_cohort_id or "", None)
    breadth_score = (cohort_breadth_scores or {}).get(primary_cohort_id or "", None)
    adjacency_band = (programme_adjacency_bands or {}).get(primary_cohort_id or "", None)
    breadth_band_val = (cohort_breadth_bands or {}).get(primary_cohort_id or "", None)
    adjacency_call = (programme_adjacency_call_ids or {}).get(primary_cohort_id or "", None)
    breadth_call = (cohort_breadth_call_ids or {}).get(primary_cohort_id or "", None)

    # Build taste profile summary
    top_tags = [t.name for t in taste_tags[:5] if t.name] if taste_tags else []
    tag_summary = ", ".join(top_tags[:3]) if top_tags else "distinctive cultural profile"

    # Build the "why" — reason from the evidence
    why_parts = []
    if primary_names:
        why_parts.append(
            f"The strongest adjacent cultural group is in the {primary_domain} domain, "
            f"featuring {', '.join(primary_names[:3])}."
        )
    if primary_affinity:
        why_parts.append(
            f"This group shows {'very high' if primary_affinity > 0.8 else 'high' if primary_affinity > 0.6 else 'moderate'} "
            f"cultural affinity (mean {primary_affinity:.2f}) with your programme's taste profile."
        )
    # Add two-sided signal explanation (M11.3: scientifically accurate labels)
    if adjacency_score is not None and breadth_score is not None:
        why_parts.append(
            f"Evidence dimensions: programme adjacency={adjacency_score:.2f} ({adjacency_band or '?'}), "
            f"cohort breadth={breadth_score:.2f} ({breadth_band_val or '?'})."
        )
    why = " ".join(why_parts) if why_parts else "Evidence supports a cultural adjacency hypothesis."

    # Cultural bridge — what connects the programme to the adjacent group
    bridge_parts = []
    if tag_summary and tag_summary != "distinctive cultural profile":
        bridge_parts.append(f"Your programme's taste profile ({tag_summary})")
    if primary_names:
        bridge_parts.append(f"shares cultural signals with {', '.join(primary_names[:2])}")
    cultural_bridge = " ".join(bridge_parts) + "." if bridge_parts else "Cultural signals connect the programme to the adjacent group."

    # Geographic signal
    geo_signal = ""
    geo_call_id = None
    if geography and geography.sufficient:
        geo_signal = (
            f"Cultural affinity concentrates in {geography.city_display} "
            f"({geography.total_cells} cells identified)."
        )
        geo_call_id = geography.call_id
    elif geography and not geography.sufficient:
        geo_signal = f"Limited geographic data for {geography.city} ({geography.total_cells} cells)."
    else:
        geo_signal = "Geographic analysis not available."

    # Programming direction
    direction_parts = []
    direction_parts.append(
        f"Test programming that connects your existing {tag_summary} profile"
    )
    if primary_names:
        direction_parts.append(
            f"with the cultural world of {', '.join(primary_names[:2])}"
        )
    if primary_domain:
        direction_parts.append(
            f"through {primary_domain}-adjacent programming"
        )
    programming_direction = " ".join(direction_parts) + "." if direction_parts else "Explore programming that bridges your current audience with the identified adjacent group."

    # Falsification condition
    falsification = (
        f"Do not continue this programming test if the {primary_domain} affinity signal "
        f"cannot be reproduced across the next comparable programme analysis. "
        f"Specifically: if a subsequent analysis of a similar programme does not produce "
        f"a {primary_domain} cohort in the top-3 ranked opportunities, the hypothesis is rejected."
    )

    # Build rejected candidates list (M11)
    rejected = []
    for cohort in (rejected_cohorts or []):
        cohort_id = cohort.cohort_id if hasattr(cohort, "cohort_id") else "?"
        domain = cohort.domain if hasattr(cohort, "domain") else "?"
        rejection = cohort.rejection if hasattr(cohort, "rejection") else None
        reason = rejection.code.value if rejection and hasattr(rejection, "code") else "unknown"
        detail = rejection.detail if rejection and hasattr(rejection, "detail") else ""
        rejected.append({
            "cohort_id": cohort_id,
            "domain": domain,
            "reason": reason,
            "detail": detail,
        })

    return ProgrammeBet(
        primary_domain=primary_domain,
        primary_cohort_name=primary_names[0] if primary_names else primary_domain,
        primary_mean_affinity=primary_affinity,
        primary_member_count=len(primary_members),
        runner_up_domain=ru_domain,
        runner_up_cohort_name=ru_names[0] if ru_names else ru_domain,
        runner_up_mean_affinity=ru_affinity,
        programme_adjacency=adjacency_score,
        adjacency_band=adjacency_band,
        adjacency_call_id=adjacency_call,
        cohort_breadth=breadth_score,
        breadth_band=breadth_band_val,
        breadth_call_id=breadth_call,
        why=why,
        cultural_bridge=cultural_bridge,
        geographic_signal=geo_signal,
        programming_direction=programming_direction,
        falsification_condition=falsification,
        rejected_candidates=rejected,
        primary_call_id=primary_call_id,
        runner_up_call_id=ru_call_id,
        geography_call_id=geo_call_id,
        data_status="measured",
    )
