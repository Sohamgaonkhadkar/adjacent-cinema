"""Test Card — structured experiment output.

The Test Card is a concise, actionable experiment specification
derived from the Programme Bet.  NOT generated by an LLM.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any

from .programme_bet import ProgrammeBet


@dataclass(frozen=True)
class TestCard:
    """A structured experiment that can be acted upon."""

    title: str
    programme_context: str
    audience_hypothesis: str
    cultural_bridge: str
    geographic_signal: str
    programming_direction: str
    primary_evidence: str
    runner_up: str
    falsification_condition: str
    #: What the programmer can actually observe to judge the test — phrased so
    #: it never predicts attendance or manufactures success numbers.
    success_criteria: str = ""
    #: A practical, bounded window for running and judging the experiment.
    observation_window: str = ""
    provenance: dict[str, Any] = field(default_factory=dict)
    data_status: str = "measured"

    def to_dict(self) -> dict[str, Any]:
        return {
            "title": self.title,
            "programme_context": self.programme_context,
            "audience_hypothesis": self.audience_hypothesis,
            "cultural_bridge": self.cultural_bridge,
            "geographic_signal": self.geographic_signal,
            "programming_direction": self.programming_direction,
            "primary_evidence": self.primary_evidence,
            "runner_up": self.runner_up,
            "falsification_condition": self.falsification_condition,
            "success_criteria": self.success_criteria,
            "observation_window": self.observation_window,
            "provenance": self.provenance,
            "data_status": self.data_status,
        }


def build_test_card(
    bet: ProgrammeBet,
    resolved_names: list[str],
    city: str,
) -> TestCard:
    """Build a Test Card from a Programme Bet."""
    # Title
    title = f"Test: {bet.primary_domain.title()} Adjacency for {city}"

    # Programme context
    programme_context = (
        f"Programme of {len(resolved_names)} film(s): {', '.join(resolved_names[:3])}"
        + (f" and {len(resolved_names) - 3} more" if len(resolved_names) > 3 else "")
        + "."
    )

    # Audience hypothesis — phrased as a testable existence claim, never a
    # size, attendance, or revenue estimate.
    others = bet.primary_member_count - 1
    if others > 0:
        represented_by = f"{bet.primary_cohort_name} and {others} similar entit{'y' if others == 1 else 'ies'}"
    else:
        represented_by = f"{bet.primary_cohort_name} (the single qualifying entity found)"
    audience_hypothesis = (
        f"A culturally aligned audience exists in the {bet.primary_domain} domain, "
        f"represented by {represented_by}, "
        f"with mean cultural affinity {bet.primary_mean_affinity:.2f}."
    )

    # Runner-up summary
    runner_up = "No runner-up identified."
    if bet.runner_up_domain and bet.runner_up_cohort_name:
        runner_up = (
            f"Runner-up: {bet.runner_up_cohort_name} in the {bet.runner_up_domain} domain"
            + (f" (affinity {bet.runner_up_mean_affinity:.2f})" if bet.runner_up_mean_affinity else "")
            + "."
        )

    # Observable success criteria — what the programmer can actually check.
    # Deliberately qualitative: Adjacent has no attendance data and predicts
    # no numbers, so success is defined by observation, not by a forecast.
    success_criteria = (
        f"The test succeeds if both observations hold: (1) the {bet.primary_domain} "
        f"adjacency signal is reproduced when this analysis is re-run on the tested "
        f"programme, and (2) your own records for the test screening show an audience "
        f"engaging with the {bet.primary_domain}-adjacent direction you programmed "
        f"(for example ticket buyers responding to the adjacency, or repeat interest "
        f"in the strand). Adjacent predicts no attendance figures — judge by what you "
        f"observe at your venue."
    )

    # Practical observation window — bounded, no invented results.
    observation_window = (
        "Screen the test programme within your next comparable season, then re-run "
        "this analysis once after its first screening. One comparable season is "
        "enough to confirm or falsify the adjacency signal; longer windows add "
        "observations but do not change the falsification condition."
    )

    # Provenance — links the card back to the exact bet and its Qloo calls.
    provenance: dict[str, Any] = {
        "primary_call_id": bet.primary_call_id,
        "runner_up_call_id": bet.runner_up_call_id,
        "geography_call_id": bet.geography_call_id,
        "primary_cohort_id": bet.primary_cohort_id,
        "data_status": bet.data_status,
    }

    return TestCard(
        title=title,
        programme_context=programme_context,
        audience_hypothesis=audience_hypothesis,
        cultural_bridge=bet.cultural_bridge,
        geographic_signal=bet.geographic_signal,
        programming_direction=bet.programming_direction,
        primary_evidence=bet.why,
        runner_up=runner_up,
        falsification_condition=bet.falsification_condition,
        success_criteria=success_criteria,
        observation_window=observation_window,
        provenance=provenance,
        data_status=bet.data_status,
    )
